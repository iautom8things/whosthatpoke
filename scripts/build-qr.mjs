// Writes src/data/playQr.ts: the QR code for the public game URL, as rows of 0 and 1.
// The app draws it (src/ui/components/QrCode.tsx), so it works offline and needs no encoder at runtime.
//   node scripts/build-qr.mjs
import { writeFileSync } from "node:fs";
import QRCode from "qrcode";

const PLAY_URL = "https://iautom8things.github.io/whosthatpoke/";

// Level Q (25% recovery) leaves room for the Poké Ball drawn over the center.
const qr = QRCode.create(PLAY_URL, { errorCorrectionLevel: "Q" });
const { size, data } = qr.modules;
const rows = Array.from({ length: size }, (_, y) => Array.from(data.subarray(y * size, (y + 1) * size)).join(""));

const out = new URL("../src/data/playQr.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/build-qr.mjs. Change the URL there and run it again.
export const PLAY_URL = ${JSON.stringify(PLAY_URL)};

/** QR code for PLAY_URL: version ${qr.version}, error correction Q, mask ${qr.maskPattern}. "1" is a dark module. */
export const PLAY_QR: readonly string[] = [
${rows.map((r) => `  "${r}",`).join("\n")}
];
`,
);
console.log(`version ${qr.version}, ${size}x${size} modules -> ${out.pathname}`);
